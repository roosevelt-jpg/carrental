const localeMap = new Map(LOCALES.map((locale) => [locale.code, locale]));

export function getLocale(code: string | null | undefined): LocaleOption {
  const normalized = code?.trim().toLowerCase().split("-")[0] ?? "en";
  return localeMap.get(normalized) ?? localeMap.get("en")!;
}

export function isSupportedLocale(code: string) {
  return localeMap.has(code.trim().toLowerCase().split("-")[0]);
}

export function isRtlLocale(code: string) {
  return Boolean(getLocale(code).rtl);
}
